# Lists
names = ["Ibtisam", "Adnan"]
print(names)

# Tuples
tuples = ("Ibtisam", "Adnan")
print(tuples)

# Dictionaries
students = {
    "name" : "Ibtisam",
    "age" : "20",
    "gender" : "male"
    }

print(students.keys())
print(students.values())
print(students.items())


# Sets
sets = {1, 1, 2, 5, 4}
print(sets)

# Union, Intersection, Difference
set1 = {1, 2, 3, 4}
set2 = {3, 4, 5, 6}

print(set1 | set2)
print(set1 & set2)
print(set1 - set2)

